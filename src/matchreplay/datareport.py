"""Checks that the ingested data is complete and consistent, before anything is built on it.

    python -m matchreplay.datareport     # writes reports/data.md and .json

The key check: replaying a match's events must give its official final score. Goals come from
shots that score plus own goals; penalty shoot-outs (period 5) don't count toward the score.
If this fails, every live number the pipeline computes would be wrong.
"""

from __future__ import annotations

import json

import pandas as pd

from matchreplay.ingest import COMPETITIONS
from matchreplay.paths import MATCHES, REPORTS

SHOOTOUT = 5


def load(key: str, table: str) -> pd.DataFrame:
    return pd.read_parquet(MATCHES / key / f"{table}.parquet")


def goals_from_events(events: pd.DataFrame, matches: pd.DataFrame) -> pd.DataFrame:
    """Final score rebuilt from the event stream, per match and side."""
    play = events[events["period"] < SHOOTOUT]
    scored = play[(play["type"] == "Shot") & (play["outcome"] == "Goal")][["match_id", "team"]]
    # "Own Goal For" is recorded for the team that benefits
    own = play[play["type"] == "Own Goal For"][["match_id", "team"]]
    goals = pd.concat([scored, own]).groupby(["match_id", "team"]).size().rename("goals").reset_index()
    m = matches[["match_id", "home", "away", "home_score", "away_score"]]
    home = m.merge(goals, left_on=["match_id", "home"], right_on=["match_id", "team"], how="left")["goals"].fillna(0)
    away = m.merge(goals, left_on=["match_id", "away"], right_on=["match_id", "team"], how="left")["goals"].fillna(0)
    return m.assign(home_rebuilt=home.astype(int).to_numpy(), away_rebuilt=away.astype(int).to_numpy())


def summarise(key: str) -> dict:
    matches, events, frames = load(key, "matches"), load(key, "events"), load(key, "frames")
    check = goals_from_events(events, matches)
    bad = check[(check["home_score"] != check["home_rebuilt"]) | (check["away_score"] != check["away_rebuilt"])]
    per_match = events.groupby("match_id").size()
    return {
        "matches": len(matches),
        "events": len(events),
        "events_per_match": round(float(per_match.mean())),
        "goals": int(check["home_score"].sum() + check["away_score"].sum()),
        "shots": int((events["type"] == "Shot").sum()),
        "xg_total": round(float(events["xg"].sum()), 1),
        "matches_with_360": int(frames.query("source == '360'")["match_id"].nunique()),
        "shot_frames": int(frames.query("source == 'shot'")["event_id"].nunique()),
        "score_mismatches": bad[["match_id", "home", "away", "home_score", "away_score",
                                 "home_rebuilt", "away_rebuilt"]].to_dict("records"),
        "extra_time_matches": int(events[events["period"].isin([3, 4])]["match_id"].nunique()),
        "shootouts": int(events[events["period"] == SHOOTOUT]["match_id"].nunique()),
    }


def to_markdown(report: dict) -> str:
    lines = ["# Data report", "",
             "Generated by `python -m matchreplay.datareport`. Source: Hudl StatsBomb open data.", "",
             "| Competition | Matches | Events | Events / match | Goals | Shots | xG | With 360 | Extra time "
             "| Shoot-outs | Score check |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for label, r in report.items():
        ok = "all match" if not r["score_mismatches"] else f"{len(r['score_mismatches'])} differ"
        lines.append(f"| {label} | {r['matches']} | {r['events']:,} | {r['events_per_match']:,} | {r['goals']} | "
                     f"{r['shots']:,} | {r['xg_total']} | {r['matches_with_360']} | {r['extra_time_matches']} | "
                     f"{r['shootouts']} | {ok} |")
    total = sum(r["matches"] for r in report.values())
    lines += ["", f"{total} matches in total. \"Score check\" rebuilds each final score from the event stream "
              "(goals and own goals, shoot-outs excluded) and compares it with the official result.", ""]
    for label, r in report.items():
        for m in r["score_mismatches"]:
            lines.append(f"- {label}: {m['home']} {m['home_score']}-{m['away_score']} {m['away']}, events give "
                         f"{m['home_rebuilt']}-{m['away_rebuilt']} (match {m['match_id']})")
    return "\n".join(lines) + "\n"


def main() -> None:
    report = {c.label: summarise(c.key) for c in COMPETITIONS if (MATCHES / c.key / "events.parquet").exists()}
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "data.json").write_text(json.dumps(report, indent=1))
    (REPORTS / "data.md").write_text(to_markdown(report), encoding="utf-8")
    print((REPORTS / "data.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
